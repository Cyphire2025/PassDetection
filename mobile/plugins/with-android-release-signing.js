const { withAppBuildGradle } = require('@expo/config-plugins');

const MODULE_NAME = 'GCAndroidReleaseSigning';
const DECLARATION_MARKER_START = '// @generated by with-android-release-signing: declarations';
const DECLARATION_MARKER_END = '// @end generated by with-android-release-signing: declarations';
const SIGNING_CONFIG_MARKER_START = '        // @generated by with-android-release-signing: signing-config';
const SIGNING_CONFIG_MARKER_END = '        // @end generated by with-android-release-signing: signing-config';
const RELEASE_BINDING_MARKER_START = '            // @generated by with-android-release-signing: release-binding';
const RELEASE_BINDING_MARKER_END = '            // @end generated by with-android-release-signing: release-binding';

const ALL_MARKERS = Object.freeze([
  DECLARATION_MARKER_START,
  DECLARATION_MARKER_END,
  SIGNING_CONFIG_MARKER_START,
  SIGNING_CONFIG_MARKER_END,
  RELEASE_BINDING_MARKER_START,
  RELEASE_BINDING_MARKER_END,
]);

const DECLARATIONS = `${DECLARATION_MARKER_START}
// Release credentials are read only by Gradle from its process environment.
// Keep values out of Expo config, generated properties, logs, and source control.
def gcReleaseSigningVariableNames = [
    'GC_ANDROID_KEYSTORE_FILE',
    'GC_ANDROID_KEYSTORE_PASSWORD',
    'GC_ANDROID_KEY_ALIAS',
    'GC_ANDROID_KEY_PASSWORD',
]
def gcReleaseSigningEnvironment = gcReleaseSigningVariableNames.collectEntries { variableName ->
    [(variableName): System.getenv(variableName)]
}
def gcReleaseSigningPresentCount = gcReleaseSigningEnvironment.values().count { value ->
    value != null && !value.isEmpty()
}
if (gcReleaseSigningPresentCount > 0 && gcReleaseSigningPresentCount < gcReleaseSigningVariableNames.size()) {
    throw new GradleException(
        'Android release signing is partially configured. Set all four GC_ANDROID release signing environment variables; values are never logged.'
    )
}
def gcReleaseSigningConfigured = gcReleaseSigningPresentCount == gcReleaseSigningVariableNames.size()
def gcIsReleaseArtifactTask = { task ->
    def taskName = task.name
    ((taskName.startsWith('assemble') || taskName.startsWith('bundle')) && taskName.endsWith('Release')) ||
        taskName.startsWith('packageRelease') ||
        taskName.startsWith('signRelease')
}
gradle.taskGraph.whenReady { taskGraph ->
    if (taskGraph.allTasks.any { task -> gcIsReleaseArtifactTask(task) }) {
        if (!gcReleaseSigningConfigured) {
            throw new GradleException(
                'Android release signing is required. Set all four GC_ANDROID release signing environment variables.'
            )
        }
        if (!file(gcReleaseSigningEnvironment['GC_ANDROID_KEYSTORE_FILE']).isFile()) {
            throw new GradleException('Android release signing keystore is not a readable file.')
        }
    }
}
${DECLARATION_MARKER_END}`;

const SIGNING_CONFIG = `${SIGNING_CONFIG_MARKER_START}
        if (gcReleaseSigningConfigured) {
            release {
                storeFile file(gcReleaseSigningEnvironment['GC_ANDROID_KEYSTORE_FILE'])
                storePassword gcReleaseSigningEnvironment['GC_ANDROID_KEYSTORE_PASSWORD']
                keyAlias gcReleaseSigningEnvironment['GC_ANDROID_KEY_ALIAS']
                keyPassword gcReleaseSigningEnvironment['GC_ANDROID_KEY_PASSWORD']
            }
        }
${SIGNING_CONFIG_MARKER_END}`;

const RELEASE_BINDING = `${RELEASE_BINDING_MARKER_START}
            if (gcReleaseSigningConfigured) {
                signingConfig signingConfigs.release
            } else {
                signingConfig null
            }
${RELEASE_BINDING_MARKER_END}`;

function markerCount(contents, marker) {
  return contents.split(marker).length - 1;
}

function assertMarkerState(contents) {
  const counts = ALL_MARKERS.map((marker) => markerCount(contents, marker));
  if (counts.every((count) => count === 0)) return false;
  if (counts.every((count) => count === 1)) return true;
  throw new Error(`${MODULE_NAME} found incomplete or duplicate generated Gradle markers.`);
}

function replaceExactlyOnce(contents, pattern, replacement, missingMessage) {
  const matches = contents.match(new RegExp(pattern.source, pattern.flags.includes('g')
    ? pattern.flags
    : `${pattern.flags}g`));
  if (matches?.length !== 1) {
    throw new Error(`${MODULE_NAME} ${missingMessage}`);
  }
  return contents.replace(pattern, replacement);
}

function patchAppBuildGradle(contents) {
  if (typeof contents !== 'string') {
    throw new TypeError(`${MODULE_NAME} requires Android app Gradle source text.`);
  }
  if (assertMarkerState(contents)) return contents;

  let next = replaceExactlyOnce(
    contents,
    /^android\s*\{/m,
    `${DECLARATIONS}\n\nandroid {`,
    'could not find the Android configuration block.',
  );

  next = replaceExactlyOnce(
    next,
    /(\r?\n    signingConfigs\s*\{[\s\S]*?)(\r?\n    \}\r?\n    buildTypes\s*\{)/,
    `$1\n${SIGNING_CONFIG}$2`,
    'could not find the generated signingConfigs/buildTypes boundary.',
  );

  next = replaceExactlyOnce(
    next,
    /(\r?\n        release\s*\{[\s\S]*?)^[ \t]*signingConfig\s+signingConfigs\.debug[ \t]*$/m,
    `$1${RELEASE_BINDING}`,
    'could not find the generated debug signing fallback in the release build type.',
  );

  return next;
}

module.exports = function withAndroidReleaseSigning(config) {
  return withAppBuildGradle(config, (gradleConfig) => {
    if (gradleConfig.modResults.language !== 'groovy') {
      throw new Error(`${MODULE_NAME} supports only a Groovy android/app/build.gradle file.`);
    }
    gradleConfig.modResults.contents = patchAppBuildGradle(
      gradleConfig.modResults.contents,
    );
    return gradleConfig;
  });
};

module.exports.patchAppBuildGradle = patchAppBuildGradle;
