/* global __dirname */

const fs = require('node:fs/promises');
const path = require('node:path');

const {
  withAppBuildGradle,
  withDangerousMod,
  withMainApplication,
  withProjectBuildGradle,
} = require('@expo/config-plugins');

const MODULE_NAME = 'GCFaceLiveness';
const PACKAGE_REGISTRATION = '          add(GCFaceLivenessPackage())';
const KOTLIN_VERSION = '2.2.0';
const LIVENESS_VERSION = '1.11.0';
const AMPLIFY_AUTH_VERSION = '2.38.1';
const COMPOSE_BOM_VERSION = '2026.03.00';
const ACTIVITY_COMPOSE_VERSION = '1.13.0';
const DESUGAR_VERSION = '2.1.5';
const PROJECT_MARKER_START = '        // @generated by with-android-face-liveness';
const PROJECT_MARKER_END = '        // @end generated by with-android-face-liveness';
const APP_MARKER_START = '// @generated by with-android-face-liveness';
const APP_MARKER_END = '// @end generated by with-android-face-liveness';
const TEMPLATE_ROOT = path.join(__dirname, 'android-face-liveness');

function assertAndroidPackage(value) {
  if (typeof value !== 'string' || !/^[A-Za-z][A-Za-z0-9_]*(?:\.[A-Za-z][A-Za-z0-9_]*)+$/.test(value)) {
    throw new Error(`${MODULE_NAME} requires a valid Expo android.package before prebuild.`);
  }
  return value;
}

function resolveFaceLivenessOptions(options = {}) {
  const enabled = options.enabled === true;
  if (!enabled) return Object.freeze({ enabled: false, region: null, identityPoolId: null });

  const region = typeof options.region === 'string' ? options.region.trim() : '';
  const identityPoolId = typeof options.identityPoolId === 'string'
    ? options.identityPoolId.trim()
    : '';
  if (!/^[a-z]{2}(?:-gov)?-[a-z]+-\d$/.test(region) || region.length > 32) {
    throw new Error(`${MODULE_NAME} requires a bounded AWS region when enabled.`);
  }
  const identityPoolPattern = new RegExp(`^${region.replaceAll('-', '\\-')}:` +
    '[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[1-5][0-9a-fA-F]{3}-[89abAB][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$');
  if (!identityPoolPattern.test(identityPoolId) || identityPoolId.length > 128) {
    throw new Error(`${MODULE_NAME} requires an Identity Pool ID in the configured region when enabled.`);
  }
  return Object.freeze({ enabled: true, region, identityPoolId });
}

function patchMainApplication(contents) {
  if (contents.includes(PACKAGE_REGISTRATION.trim())) return contents;
  const anchor = /(PackageList\(this\)\.packages\.apply \{\r?\n)/;
  if (!anchor.test(contents)) {
    throw new Error(`${MODULE_NAME} could not find the PackageList registration block.`);
  }
  return contents.replace(anchor, `$1${PACKAGE_REGISTRATION}\n`);
}

function stripMarkedBlock(contents, start, end, replacement = '') {
  const startIndex = contents.indexOf(start);
  if (startIndex < 0) return contents;
  const endIndex = contents.indexOf(end, startIndex);
  if (endIndex < 0) throw new Error(`${MODULE_NAME} found an incomplete generated Gradle block.`);
  const after = endIndex + end.length;
  return `${contents.slice(0, startIndex)}${replacement}${contents.slice(after)}`;
}

function patchProjectBuildGradle(contents, enabled) {
  let next = stripMarkedBlock(
    contents,
    PROJECT_MARKER_START,
    PROJECT_MARKER_END,
    "        classpath('org.jetbrains.kotlin:kotlin-gradle-plugin')",
  );
  if (!enabled) return next;
  const kotlinClasspath = /^[ \t]*classpath\((['"])org\.jetbrains\.kotlin:kotlin-gradle-plugin\1\)[ \t]*$/m;
  if (!kotlinClasspath.test(next)) {
    throw new Error(`${MODULE_NAME} could not find the Kotlin Gradle classpath.`);
  }
  const replacement = [
    PROJECT_MARKER_START,
    `        classpath('org.jetbrains.kotlin:kotlin-gradle-plugin:${KOTLIN_VERSION}')`,
    `        classpath('org.jetbrains.kotlin.plugin.compose:org.jetbrains.kotlin.plugin.compose.gradle.plugin:${KOTLIN_VERSION}')`,
    PROJECT_MARKER_END,
  ].join('\n');
  return next.replace(kotlinClasspath, replacement);
}

function patchAppBuildGradle(contents, enabled) {
  let next = stripMarkedBlock(contents, APP_MARKER_START, APP_MARKER_END).replace(/\n{3,}/g, '\n\n');
  if (!enabled) return next;
  const dependenciesAnchor = /\r?\ndependencies\s*\{/;
  if (!dependenciesAnchor.test(next)) {
    throw new Error(`${MODULE_NAME} could not find the Android dependencies block.`);
  }
  const block = [
    APP_MARKER_START,
    'apply plugin: "org.jetbrains.kotlin.plugin.compose"',
    '',
    'android {',
    '    buildFeatures {',
    '        compose true',
    '    }',
    '    compileOptions {',
    '        coreLibraryDesugaringEnabled true',
    '    }',
    '}',
    '',
    'dependencies {',
    `    implementation(platform("androidx.compose:compose-bom:${COMPOSE_BOM_VERSION}"))`,
    `    implementation("androidx.activity:activity-compose:${ACTIVITY_COMPOSE_VERSION}")`,
    `    implementation("com.amplifyframework.ui:liveness:${LIVENESS_VERSION}")`,
    `    implementation("com.amplifyframework:aws-auth-cognito:${AMPLIFY_AUTH_VERSION}")`,
    `    coreLibraryDesugaring("com.android.tools:desugar_jdk_libs:${DESUGAR_VERSION}")`,
    '}',
    APP_MARKER_END,
    '',
  ].join('\n');
  return next.replace(dependenciesAnchor, `\n${block}dependencies {`);
}

function amplifyConfiguration(options) {
  return JSON.stringify({
    UserAgent: 'aws-amplify-cli/2.0',
    Version: '1.0',
    auth: {
      plugins: {
        awsCognitoAuthPlugin: {
          IdentityManager: { Default: {} },
          CredentialsProvider: {
            CognitoIdentity: {
              Default: {
                PoolId: options.identityPoolId,
                Region: options.region,
              },
            },
          },
        },
      },
    },
  }, null, 2);
}

async function writeNativeFiles(platformProjectRoot, androidPackage, options) {
  const templateName = options.enabled
    ? 'GCFaceLivenessPackage.enabled.kt.template'
    : 'GCFaceLivenessPackage.disabled.kt.template';
  const template = await fs.readFile(path.join(TEMPLATE_ROOT, templateName), 'utf8');
  const rendered = template
    .replaceAll('__ANDROID_PACKAGE__', androidPackage)
    .replaceAll('__AWS_REGION__', options.region ?? 'disabled');
  const sourcePath = path.join(
    platformProjectRoot,
    'app',
    'src',
    'main',
    'java',
    ...androidPackage.split('.'),
    'GCFaceLivenessPackage.kt',
  );
  await fs.mkdir(path.dirname(sourcePath), { recursive: true });
  await fs.writeFile(sourcePath, rendered, 'utf8');

  const rawDirectory = path.join(platformProjectRoot, 'app', 'src', 'main', 'res', 'raw');
  const configPath = path.join(rawDirectory, 'gc_face_liveness_amplifyconfiguration.json');
  if (options.enabled) {
    await fs.mkdir(rawDirectory, { recursive: true });
    await fs.writeFile(configPath, `${amplifyConfiguration(options)}\n`, 'utf8');
  } else {
    await fs.rm(configPath, { force: true });
  }
}

module.exports = function withAndroidFaceLiveness(config, rawOptions) {
  const options = resolveFaceLivenessOptions(rawOptions);
  const androidPackage = assertAndroidPackage(config.android?.package);
  let nextConfig = withProjectBuildGradle(config, (gradleConfig) => {
    gradleConfig.modResults.contents = patchProjectBuildGradle(
      gradleConfig.modResults.contents,
      options.enabled,
    );
    return gradleConfig;
  });
  nextConfig = withAppBuildGradle(nextConfig, (gradleConfig) => {
    gradleConfig.modResults.contents = patchAppBuildGradle(
      gradleConfig.modResults.contents,
      options.enabled,
    );
    return gradleConfig;
  });
  nextConfig = withMainApplication(nextConfig, (mainApplicationConfig) => {
    mainApplicationConfig.modResults.contents = patchMainApplication(
      mainApplicationConfig.modResults.contents,
    );
    return mainApplicationConfig;
  });
  nextConfig = withDangerousMod(nextConfig, [
    'android',
    async (dangerousConfig) => {
      await writeNativeFiles(
        dangerousConfig.modRequest.platformProjectRoot,
        androidPackage,
        options,
      );
      return dangerousConfig;
    },
  ]);
  return nextConfig;
};

module.exports.resolveFaceLivenessOptions = resolveFaceLivenessOptions;
module.exports.patchMainApplication = patchMainApplication;
module.exports.patchProjectBuildGradle = patchProjectBuildGradle;
module.exports.patchAppBuildGradle = patchAppBuildGradle;
module.exports.amplifyConfiguration = amplifyConfiguration;
module.exports.writeNativeFiles = writeNativeFiles;
module.exports.versions = Object.freeze({
  kotlin: KOTLIN_VERSION,
  liveness: LIVENESS_VERSION,
  amplifyAuth: AMPLIFY_AUTH_VERSION,
  composeBom: COMPOSE_BOM_VERSION,
  activityCompose: ACTIVITY_COMPOSE_VERSION,
  desugar: DESUGAR_VERSION,
});
